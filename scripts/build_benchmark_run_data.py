def _load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as stream:
        return json.load(stream)


def _question_payload(question: dict[str, Any]) -> dict[str, Any]:
    return {
        "id": question["id"],
        "category": question["category"],
        "category_label": question.get("category_label", ""),
        "task_family_id": question.get("task_family_id", ""),
        "prompt": question["prompt"],
        "expected_answer": question["expected_answer"],
    }


def _score_raw_run(raw_path: Path, dataset: dict[str, dict[str, Any]]) -> list[dict[str, Any]]:
    payload = _load_json(raw_path)
    _input_meta, records = score_run.normalize_run_payload(payload)
    return [score_run.score_record(record, dataset) for record in records]


def _answer_payload(record: dict[str, Any]) -> dict[str, Any]:
    return {
        "answer": record.get("answer") or "",
        "reasoning": record.get("reasoning") or "",
        "correct": record.get("score_answer") == 1,
        "score_reason": record.get("score_reason") or "",
    }


def build_payload(run_dir: Path = DEFAULT_RUN_DIR) -> dict[str, Any]:
    questions = run_benchmark.default_questions(_load_json(run_benchmark.DATA_PATH))
    dataset = score_run.load_dataset(run_benchmark.DATA_PATH)
    categories = Counter(question["category"] for question in questions)

    by_question: dict[str, dict[str, Any]] = {
        question["id"]: {**_question_payload(question), "answers": {}}
        for question in questions
    }
    models: list[dict[str, Any]] = []

    for model in MODEL_RUNS:
        raw_path = Path(model["raw"])
        if not raw_path.is_absolute():
            raw_path = REPO_ROOT / raw_path
        scored = _score_raw_run(raw_path, dataset)
        correct = 0
        for record in scored:
            case_id = record["case_id"]
            if case_id not in by_question:
                continue
            if record.get("score_answer") == 1:
                correct += 1
            by_question[case_id]["answers"][model["id"]] = _answer_payload(record)

        models.append(
            {
                "id": model["id"],
                "label": model["label"],
                "correct": correct,
                "total": len(scored),
                "accuracy": round(correct / len(scored), 4) if scored else 0,
                "source": str(raw_path.relative_to(REPO_ROOT)),
            }
        )

    return {
        "benchmark": "reasoning-benchmark",
        "run_id": "usage-full-20260529-plus-gpt55-effort-20260531",
        "title": "Latest benchmark model answers",
        "summary": {
            "question_count": len(questions),
            "category_count": len(categories),
        },
        "categories": [
            {"id": category, "count": categories[category]}
            for category in sorted(categories)
        ],
        "models": models,
        "questions": [by_question[question["id"]] for question in questions],
    }


def write_data(output: Path = DEFAULT_OUTPUT, run_dir: Path = DEFAULT_RUN_DIR) -> None:
    payload = build_payload(run_dir)
    output.parent.mkdir(parents=True, exist_ok=True)
    encoded = json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=True)
    output.write_text(
        "// Generated by scripts/build_benchmark_run_data.py. Do not edit by hand.\n"
        f"window.REASONING_BENCHMARK_RUN_DATA = {encoded};\n",
        encoding="utf-8",
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Build the static latest-run answer browser data payload."
    )
    parser.add_argument(
        "--run-dir",
        type=Path,
        default=DEFAULT_RUN_DIR,
        help="Directory containing latest-run raw artifacts.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="Output path for benchmark-run-data.js",
    )
    return parser


def main() -> int:
    args = build_parser().parse_args()
    run_dir = args.run_dir if args.run_dir.is_absolute() else REPO_ROOT / args.run_dir
    output = args.output if args.output.is_absolute() else REPO_ROOT / args.output
    write_data(output=output, run_dir=run_dir)
    print(f"wrote benchmark run data: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
