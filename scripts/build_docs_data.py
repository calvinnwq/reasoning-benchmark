#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Any

import run_benchmark
import suites


REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = REPO_ROOT / "docs" / "questions-data.js"


def _load_json(path: Path) -> Any:
    with path.open("r", encoding="utf-8") as stream:
        return json.load(stream)


def _question_payload(question: dict[str, Any]) -> dict[str, Any]:
    fields = (
        "id",
        "category",
        "category_label",
        "provenance",
        "prompt",
        "expected_answer",
        "accepted_variants",
        "common_wrong_answer",
        "rationale",
        "failure_mode",
        "task_family_id",
        "evaluation",
        "ambiguity",
        "cooperative_intent",
        "calibration",
    )
    return {field: question[field] for field in fields if field in question}


def _category_payload(questions: list[dict[str, Any]]) -> list[dict[str, Any]]:
    counts = Counter(question["category"] for question in questions)
    labels: dict[str, str] = {}
    for question in questions:
        labels.setdefault(question["category"], question.get("category_label", ""))

    return [
        {
            "id": category,
            "label": labels.get(category, category),
            "count": counts[category],
        }
        for category in sorted(counts)
    ]


def _suite_payload(questions: list[dict[str, Any]]) -> list[dict[str, Any]]:
    default_questions = run_benchmark.default_questions(questions)
    payload = [
        {
            "id": run_benchmark.DEFAULT_SUITE_ID,
            "name": "Default Auto-scored Slice",
            "description": "All non-optional auto-scored benchmark cases.",
            "case_ids": [question["id"] for question in default_questions],
        }
    ]

    for suite_id in suites.list_available_suites():
        manifest = suites.load_suite_manifest(suite_id)
        payload.append(
            {
                "id": suite_id,
                "name": manifest["name"],
                "description": manifest["description"],
                "case_ids": manifest["case_ids"],
            }
        )
    return payload


def build_payload() -> dict[str, Any]:
    questions = _load_json(run_benchmark.DATA_PATH)
    category_counts = _category_payload(questions)
    suites_payload = _suite_payload(questions)

    return {
        "benchmark": "reasoning-benchmark",
        "summary": {
            "question_count": len(questions),
            "default_question_count": len(run_benchmark.default_questions(questions)),
            "category_count": len(category_counts),
            "suite_count": len(suites_payload),
        },
        "categories": category_counts,
        "suites": suites_payload,
        "questions": [_question_payload(question) for question in questions],
    }


def write_data(output: Path = DEFAULT_OUTPUT) -> None:
    payload = build_payload()
    output.parent.mkdir(parents=True, exist_ok=True)
    encoded = json.dumps(payload, indent=2, sort_keys=True, ensure_ascii=True)
    output.write_text(
        "// Generated by scripts/build_docs_data.py. Do not edit by hand.\n"
        f"window.REASONING_BENCHMARK_DATA = {encoded};\n",
        encoding="utf-8",
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Build the static GitHub Pages question data payload."
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="Output path for questions-data.js",
    )
    return parser


def main() -> int:
    args = build_parser().parse_args()
    output = args.output
    if not output.is_absolute():
        output = REPO_ROOT / output
    write_data(output)
    print(f"wrote docs data: {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
