REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.append(str(REPO_ROOT / "scripts"))

import build_docs_data
import build_benchmark_run_data
import run_benchmark


def _read_data(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    match = re.fullmatch(
        r"// Generated by scripts/build_docs_data\.py\. Do not edit by hand\.\n"
        r"window\.REASONING_BENCHMARK_DATA = (.*);\n",
        text,
        flags=re.DOTALL,
    )
    if not match:
        raise AssertionError("docs data file does not match the expected JS wrapper")
    return json.loads(match.group(1))


def _read_run_data(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    match = re.fullmatch(
        r"// Generated by scripts/build_benchmark_run_data\.py\. Do not edit by hand\.\n"
        r"window\.REASONING_BENCHMARK_RUN_DATA = (.*);\n",
        text,
        flags=re.DOTALL,
    )
    if not match:
        raise AssertionError("benchmark run data file does not match the expected JS wrapper")
    return json.loads(match.group(1))


class DocsSiteTests(unittest.TestCase):
    def test_build_docs_data_payload_includes_questions_categories_and_suites(self) -> None:
        payload = build_docs_data.build_payload()

        self.assertEqual("reasoning-benchmark", payload["benchmark"])
        self.assertEqual(144, payload["summary"]["question_count"])
        self.assertEqual(94, payload["summary"]["default_question_count"])
        self.assertEqual(8, payload["summary"]["category_count"])

        category_ids = {category["id"] for category in payload["categories"]}
        self.assertEqual({"CR", "GG", "IA", "LP", "MC", "PR", "SP", "TW"}, category_ids)

        suite_ids = {suite["id"] for suite in payload["suites"]}
        self.assertEqual({"default", "holdout", "instruction-ambiguity", "starter"}, suite_ids)

        first_question = payload["questions"][0]
        self.assertEqual("GG-01", first_question["id"])
        self.assertIn("prompt", first_question)
        self.assertIn("expected_answer", first_question)

    def test_committed_docs_data_is_fresh(self) -> None:
        with tempfile.TemporaryDirectory() as tmp_dir:
            generated_path = Path(tmp_dir) / "questions-data.js"
            build_docs_data.write_data(generated_path)

            committed_path = REPO_ROOT / "docs" / "questions-data.js"
            self.assertEqual(
                _read_data(generated_path),
                _read_data(committed_path),
            )

    def test_committed_benchmark_run_data_is_fresh(self) -> None:
        with tempfile.TemporaryDirectory() as tmp_dir:
            generated_path = Path(tmp_dir) / "benchmark-run-data.js"
            build_benchmark_run_data.write_data(generated_path)

            committed_path = (
                REPO_ROOT
                / "docs"
                / "runs"
                / "gpt-opus-2026-05"
                / "benchmark-run-data.js"
            )
            self.assertEqual(
                _read_run_data(generated_path),
                _read_run_data(committed_path),
            )

    def test_benchmark_run_data_includes_model_answers_and_scores(self) -> None:
        payload = build_benchmark_run_data.build_payload()

        scores = {model["id"]: model["correct"] for model in payload["models"]}
        self.assertEqual(
            {
                "gpt-5.4-xhigh": 93,
                "gpt-5.5-medium": 92,
                "gpt-5.5-high": 93,
                "gpt-5.5-xhigh": 93,
                "opus-4.7-max": 93,
                "opus-4.8-max": 92,
            },
            scores,
        )

        first_question = payload["questions"][0]
        self.assertEqual("GG-01", first_question["id"])
        self.assertIn("expected_answer", first_question)
        self.assertEqual(
            {
                "gpt-5.4-xhigh",
                "gpt-5.5-medium",
                "gpt-5.5-high",
                "gpt-5.5-xhigh",
                "opus-4.7-max",
                "opus-4.8-max",
            },
            set(first_question["answers"]),
        )

