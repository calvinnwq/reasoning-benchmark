    def test_docs_pages_include_theme_switcher(self) -> None:
        pages = [
            (REPO_ROOT / "docs" / "index.html", 'src="theme.js"'),
            (REPO_ROOT / "docs" / "questions.html", 'src="theme.js"'),
            (
                REPO_ROOT / "docs" / "guides" / "run-locally.html",
                'src="../theme.js"',
            ),
            (
                REPO_ROOT / "docs" / "runs" / "gpt-opus-2026-05" / "index.html",
                'src="../../theme.js"',
            ),
            (
                REPO_ROOT / "docs" / "runs" / "gpt-opus-2026-05" / "answers.html",
                'src="../../theme.js"',
            ),
        ]
        theme_js = (REPO_ROOT / "docs" / "theme.js").read_text(encoding="utf-8")
        site_css = (REPO_ROOT / "docs" / "site.css").read_text(encoding="utf-8")

        self.assertIn("reasoning-benchmark-theme", theme_js)
        self.assertIn('html[data-theme="dark"]', site_css)
        self.assertIn(".theme-toggle .theme-icon-sun", site_css)
        self.assertIn('html[data-theme="dark"] .theme-toggle .theme-icon-moon', site_css)

