    def test_default_suite_count_matches_runner(self) -> None:
        questions = run_benchmark.load_questions()
        default_case_ids = {
            question["id"] for question in run_benchmark.default_questions(questions)
        }
        payload = build_docs_data.build_payload()
        docs_default = next(
            suite for suite in payload["suites"] if suite["id"] == "default"
        )

        self.assertEqual(len(default_case_ids), len(docs_default["case_ids"]))
        self.assertEqual(default_case_ids, set(docs_default["case_ids"]))


